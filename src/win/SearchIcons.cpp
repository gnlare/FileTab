static void DecodeRle(const RleRun* runs, size_t count, uint8_t* out, size_t outSize) {
    size_t idx = 0;
    for (size_t i = 0; i < count && idx < outSize; ++i) {
        size_t n = runs[i].count;
        if (idx + n > outSize) n = outSize - idx;
        std::fill_n(out + idx, n, runs[i].val);
        idx += n;
    }
}

static HBITMAP CreatePremultipliedDIB(const uint8_t* alpha, COLORREF color) {
    BITMAPINFO bi{};
    bi.bmiHeader.biSize = sizeof(BITMAPINFOHEADER);
    bi.bmiHeader.biWidth = 128;
    bi.bmiHeader.biHeight = -128; // top-down
    bi.bmiHeader.biPlanes = 1;
    bi.bmiHeader.biBitCount = 32;
    bi.bmiHeader.biCompression = BI_RGB;

    void* bits = nullptr;
    HBITMAP bmp = CreateDIBSection(nullptr, &bi, DIB_RGB_COLORS, &bits, nullptr, 0);
    if (!bmp || !bits) {
        if (bmp) DeleteObject(bmp);
        return nullptr;
    }

    uint32_t* px = static_cast<uint32_t*>(bits);
    uint32_t r = GetRValue(color);
    uint32_t g = GetGValue(color);
    uint32_t b = GetBValue(color);

    for (int i = 0; i < 128 * 128; ++i) {
        uint32_t a = alpha[i];
        if (a == 0) {
            px[i] = 0;
        } else {
            uint32_t pr = (r * a) / 255;
            uint32_t pg = (g * a) / 255;
            uint32_t pb = (b * a) / 255;
            px[i] = (a << 24) | (pr << 16) | (pg << 8) | pb;
        }
    }
    return bmp;
}

struct IconCache {
    std::mutex mtx;
    bool initialized = false;
    uint8_t searchAlpha[128 * 128]{};
    uint8_t filterAlpha[128 * 128]{};

    HBITMAP bmpSearchLight = nullptr;
    HBITMAP bmpSearchDark = nullptr;
    HBITMAP bmpFilterLight = nullptr;
    HBITMAP bmpFilterDark = nullptr;
    HBITMAP bmpFilterActiveLight = nullptr;
    HBITMAP bmpFilterActiveDark = nullptr;

    void Init() {
        if (initialized) return;
        std::lock_guard<std::mutex> lock(mtx);
        if (initialized) return;

        DecodeRle(kSearchRuns, sizeof(kSearchRuns) / sizeof(kSearchRuns[0]), searchAlpha, sizeof(searchAlpha));
        DecodeRle(kFilterRuns, sizeof(kFilterRuns) / sizeof(kFilterRuns[0]), filterAlpha, sizeof(filterAlpha));

        bmpSearchLight = CreatePremultipliedDIB(searchAlpha, RGB(0, 0, 0));
        bmpSearchDark = CreatePremultipliedDIB(searchAlpha, RGB(255, 255, 255));

        bmpFilterLight = CreatePremultipliedDIB(filterAlpha, RGB(0, 0, 0));
        bmpFilterDark = CreatePremultipliedDIB(filterAlpha, RGB(255, 255, 255));
        bmpFilterActiveLight = CreatePremultipliedDIB(filterAlpha, RGB(0, 120, 215));
        bmpFilterActiveDark = CreatePremultipliedDIB(filterAlpha, RGB(0, 150, 255));

        initialized = true;
    }

    void Cleanup() {
        std::lock_guard<std::mutex> lock(mtx);
        if (bmpSearchLight) { DeleteObject(bmpSearchLight); bmpSearchLight = nullptr; }
        if (bmpSearchDark) { DeleteObject(bmpSearchDark); bmpSearchDark = nullptr; }
        if (bmpFilterLight) { DeleteObject(bmpFilterLight); bmpFilterLight = nullptr; }
        if (bmpFilterDark) { DeleteObject(bmpFilterDark); bmpFilterDark = nullptr; }
        if (bmpFilterActiveLight) { DeleteObject(bmpFilterActiveLight); bmpFilterActiveLight = nullptr; }
        if (bmpFilterActiveDark) { DeleteObject(bmpFilterActiveDark); bmpFilterActiveDark = nullptr; }
        initialized = false;
    }
};

static IconCache s_cache;

static void DrawBitmapAlpha(HDC hdc, HDC scratchDc, HBITMAP bmp, const RECT& rcDest) {
    if (!bmp || !hdc || !scratchDc) return;
    int w = rcDest.right - rcDest.left;
    int h = rcDest.bottom - rcDest.top;
    if (w <= 0 || h <= 0) return;

    HGDIOBJ old = SelectObject(scratchDc, bmp);
    int prevMode = SetStretchBltMode(hdc, HALFTONE);
    POINT ptOrg{};
    SetBrushOrgEx(hdc, 0, 0, &ptOrg);

    BLENDFUNCTION bf{AC_SRC_OVER, 0, 255, AC_SRC_ALPHA};
    AlphaBlend(hdc, rcDest.left, rcDest.top, w, h, scratchDc, 0, 0, 128, 128, bf);

    SetStretchBltMode(hdc, prevMode);
    SelectObject(scratchDc, old);
}

